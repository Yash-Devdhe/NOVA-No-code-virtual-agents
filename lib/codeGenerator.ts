import type { CustomTool, RFEdge, RFNode } from "../types/agent-builder";

type CodeLanguage = "javascript" | "typescript" | "python";

type GeneratorSettings = {
  instructions?: string;
  includeChatHistory?: boolean;
  model?: string;
  outputFormat?: "text" | "json";
  codeLanguage?: CodeLanguage;
};

type GeneratorOptions = {
  agentId?: string;
  agentName?: string;
  customTools?: CustomTool[];
  settings?: GeneratorSettings;
};

type NormalizedNode = {
  id: string;
  label: string;
  type: string;
  config: Record<string, unknown>;
  position: { x: number; y: number };
};

type ApiKeyConfig = NonNullable<CustomTool["apiKeyConfig"]>;

function escapeTemplate(value: string) {
  return String(value || "")
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

function escapePythonBlock(value: string) {
  return String(value || "").replace(/'''/g, "\\'\\'\\'");
}

function normalizeNode(node: RFNode): NormalizedNode {
  return {
    id: node.id,
    label: String(node.data?.label || node.id),
    type: String(node.data?.type || node.type || "default"),
    config: (node.data?.config || {}) as Record<string, unknown>,
    position: node.position,
  };
}

function normalizeApiKeyConfig(config: unknown): ApiKeyConfig | undefined {
  if (!config || typeof config !== "object") return undefined;
  const value = config as Record<string, unknown>;
  const authType = value.authType || value.headerType;

  if (typeof value.useApiKey !== "boolean" || typeof value.apiKey !== "string") {
    return undefined;
  }

  return {
    useApiKey: value.useApiKey,
    apiKey: value.apiKey,
    authType:
      authType === "api-key" ||
      authType === "query" ||
      authType === "custom" ||
      authType === "bearer"
        ? authType
        : "bearer",
    customHeaderName:
      typeof value.customHeaderName === "string"
        ? value.customHeaderName
        : typeof value.keyName === "string"
          ? value.keyName
          : undefined,
  };
}

function buildGeneratedToolNodes(nodes: NormalizedNode[]) {
  return nodes
    .filter((node) => node.type === "api" || node.type === "custom")
    .map((node) => {
      const config = node.config || {};
      const nestedApiKey =
        typeof config.apiKeyConfig === "object" &&
        config.apiKeyConfig &&
        "apiKey" in (config.apiKeyConfig as Record<string, unknown>)
          ? String((config.apiKeyConfig as Record<string, unknown>).apiKey || "")
          : "";

      return {
        id: node.id,
        name: String(config.apiCallName || node.label || node.id),
        description:
          node.type === "custom"
            ? "Custom tool from NOVA builder"
            : "API node from NOVA builder",
        apiUrl: String(config.apiUrl || ""),
        method: String(config.method || "GET").toUpperCase(),
        paramsSchema: config.paramsSchema || {},
        apiKey: String(config.apiKey || nestedApiKey || "").trim() || undefined,
        apiKeyConfig: normalizeApiKeyConfig(config.apiKeyConfig),
      };
    });
}

function buildApiKeys(nodes: RFNode[]) {
  const apiKeys: Record<string, string> = {};

  for (const node of nodes) {
    const config = node.data?.config as Record<string, unknown> | undefined;
    const apiKeyConfig = normalizeApiKeyConfig(config?.apiKeyConfig);
    const apiKey = apiKeyConfig?.apiKey || String(config?.apiKey || "");
    if (!apiKey) continue;
    apiKeys[node.data?.type === "llm" ? "openai" : "api"] = apiKey;
  }

  return apiKeys;
}

function buildAgentConfig(
  nodes: RFNode[],
  edges: RFEdge[],
  agentType: string,
  options: GeneratorOptions,
) {
  const settings = options.settings || {};
  const serializedNodes = nodes.map(normalizeNode);

  return {
    id: options.agentId || "",
    name: options.agentName || "NOVA Agent",
    type: agentType,
    settings: {
      instructions: settings.instructions || "",
      includeChatHistory: settings.includeChatHistory ?? true,
      model: settings.model || "gpt-5-mini",
      outputFormat: settings.outputFormat || "text",
    },
    nodes: serializedNodes,
    edges,
    customTools: (options.customTools || []).map((tool) => ({
      ...tool,
      apiKeyConfig: normalizeApiKeyConfig(tool.apiKeyConfig),
    })),
    generatedToolNodes: buildGeneratedToolNodes(serializedNodes),
  };
}

